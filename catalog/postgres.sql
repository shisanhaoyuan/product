-- PostgreSQL schema. JSON evidence stays verbatim TEXT to retain source hashes.
-- Derived searchable rows are rebuilt from the same Python overlay as SQLite.
CREATE TABLE IF NOT EXISTS migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS products(id TEXT PRIMARY KEY, source TEXT NOT NULL, asin TEXT NOT NULL, UNIQUE(source,asin));
CREATE TABLE IF NOT EXISTS listings(
 id TEXT PRIMARY KEY, product_id TEXT NOT NULL REFERENCES products(id),
 namespace TEXT NOT NULL, external_id TEXT NOT NULL, sku TEXT NOT NULL,
 store TEXT NOT NULL, brand TEXT NOT NULL, template TEXT NOT NULL,
 uploaded_at TEXT NOT NULL, observed_at TEXT NOT NULL, evidence_kind TEXT NOT NULL,
 saved INTEGER NOT NULL, complete INTEGER NOT NULL, verified INTEGER NOT NULL,
 search_text TEXT NOT NULL, data_json TEXT NOT NULL, digest TEXT NOT NULL,
 UNIQUE(namespace,external_id));
CREATE INDEX IF NOT EXISTS listing_store ON listings(store,uploaded_at);
CREATE TABLE IF NOT EXISTS variants(
 listing_id TEXT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
 sku TEXT NOT NULL, asin TEXT NOT NULL, data_json TEXT NOT NULL, PRIMARY KEY(listing_id,sku));
CREATE INDEX IF NOT EXISTS variant_asin ON variants(asin);
CREATE TABLE IF NOT EXISTS snapshots(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 listing_id TEXT NOT NULL REFERENCES listings(id), digest TEXT NOT NULL,
 observed_at TEXT NOT NULL, evidence_kind TEXT NOT NULL, data_json TEXT NOT NULL,
 UNIQUE(listing_id,digest));
CREATE TABLE IF NOT EXISTS imports(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT NOT NULL,
 namespace TEXT NOT NULL,label TEXT NOT NULL,digest TEXT NOT NULL,result_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,role TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1,
 must_change_password INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS sessions(
 token_hash TEXT PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),
 csrf_token TEXT NOT NULL,expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS session_user_idx ON sessions(user_id);
CREATE TABLE IF NOT EXISTS auth_attempts(key TEXT PRIMARY KEY,started BIGINT NOT NULL,attempts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at BIGINT NOT NULL,
 actor_id BIGINT,action TEXT NOT NULL,target TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS seller_blacklist(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,source TEXT NOT NULL,seller TEXT NOT NULL,
 source_key TEXT NOT NULL,seller_key TEXT NOT NULL,reason TEXT NOT NULL,
 active INTEGER NOT NULL DEFAULT 1,created_at TEXT NOT NULL,updated_at TEXT NOT NULL,
 search_text TEXT NOT NULL DEFAULT '',UNIQUE(source_key,seller_key));
CREATE TABLE IF NOT EXISTS seller_blacklist_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 blacklist_id BIGINT NOT NULL REFERENCES seller_blacklist(id),at TEXT NOT NULL,
 actor_id BIGINT,action TEXT NOT NULL,data_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS product_edits(
 listing_id TEXT PRIMARY KEY REFERENCES listings(id),revision INTEGER NOT NULL,
 source_digest TEXT NOT NULL,changes_json TEXT NOT NULL,updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS product_edit_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,listing_id TEXT NOT NULL REFERENCES listings(id),
 at TEXT NOT NULL,actor_id BIGINT,action TEXT NOT NULL,data_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS listing_stores(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,
 name_key TEXT NOT NULL UNIQUE,marketplace_name TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1,origin TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS prelisting_batches(
 id TEXT PRIMARY KEY,request_key TEXT NOT NULL UNIQUE,request_hash TEXT NOT NULL,status TEXT NOT NULL,
 created_at TEXT NOT NULL,updated_at TEXT NOT NULL,actor_id BIGINT,settings_json TEXT NOT NULL,preview_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS prelisting_items(
 batch_id TEXT NOT NULL REFERENCES prelisting_batches(id),listing_id TEXT NOT NULL REFERENCES listings(id),
 source_digest TEXT NOT NULL,source_json TEXT NOT NULL,PRIMARY KEY(batch_id,listing_id));
CREATE TABLE IF NOT EXISTS prelisting_claims(
 source_key TEXT NOT NULL,asin TEXT NOT NULL,store_id BIGINT NOT NULL REFERENCES listing_stores(id),
 batch_id TEXT NOT NULL REFERENCES prelisting_batches(id),UNIQUE(source_key,asin,store_id));
CREATE TABLE IF NOT EXISTS prelisting_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,batch_id TEXT NOT NULL REFERENCES prelisting_batches(id),
 at TEXT NOT NULL,actor_id BIGINT,action TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS current_listings(
 id TEXT PRIMARY KEY REFERENCES listings(id) ON DELETE CASCADE,product_id TEXT NOT NULL,
 namespace TEXT NOT NULL,external_id TEXT NOT NULL,sku TEXT NOT NULL,store TEXT NOT NULL,
 brand TEXT NOT NULL,template TEXT NOT NULL,uploaded_at TEXT NOT NULL,observed_at TEXT NOT NULL,
 evidence_kind TEXT NOT NULL,saved INTEGER NOT NULL,complete INTEGER NOT NULL,verified INTEGER NOT NULL,
 search_text TEXT NOT NULL,data_json TEXT NOT NULL,digest TEXT NOT NULL,
 source_digest TEXT NOT NULL,edit_version INTEGER NOT NULL,category TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS current_store ON current_listings(store,uploaded_at DESC,id);
CREATE INDEX IF NOT EXISTS current_category ON current_listings(category);
CREATE INDEX IF NOT EXISTS current_brand ON current_listings(brand);
CREATE TABLE IF NOT EXISTS current_listing_sellers(
 listing_id TEXT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,source_key TEXT NOT NULL,
 seller_key TEXT NOT NULL,PRIMARY KEY(listing_id,source_key,seller_key));
CREATE INDEX IF NOT EXISTS current_seller ON current_listing_sellers(source_key,seller_key);
CREATE TABLE IF NOT EXISTS image_objects(
 digest TEXT PRIMARY KEY,object_key TEXT NOT NULL,mime TEXT NOT NULL,size BIGINT NOT NULL,
 created_at TEXT NOT NULL,actor_id BIGINT,bucket TEXT NOT NULL,endpoint TEXT NOT NULL,
 backend TEXT NOT NULL DEFAULT 'oss');
ALTER TABLE image_objects ADD COLUMN IF NOT EXISTS backend TEXT NOT NULL DEFAULT 'oss';
CREATE TABLE IF NOT EXISTS migration_runs(
 source_digest TEXT PRIMARY KEY,at TEXT NOT NULL,report_json TEXT NOT NULL);
